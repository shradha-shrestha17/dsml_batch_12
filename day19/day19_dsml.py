class Employee:
  def __init__(self, nm, sal):
    self.name = nm
    self.salary = sal

  def getName(self):  #camel case
    return self.name

  def getSalary(self):
    return self.salary

class Salesoffice(Employee):
  def __init__(self, nm , sal, inc):
    super().__init__(nm, sal)
    self.incnt = inc

  def getSalary(self):
    return self.salary + self.incnt

e1 = Employee("Shradha", 89000)
print("Total salary is {} in Rs{}".format(e1.getName(), e1.getSalary()))

s1 = Salesoffice("Ram", 76000, 10000)
print("Total salary is {} in Rs{}".format(s1.getName(), s1.getSalary()))

