class BankAccount:
    def __init__(self, name, balance):
        self.name = name
        self._account_type = "Bank"
        self.__balance = balance

    def deposit(self, amount):
      if amount>0:
        self.__balance += amount
        # Added print for deposit success, consistency with withdraw
        print(f"Deposited: {amount}")
      else:
        print("Invalid deposit amount")

    def withdraw(self, amount):
        if amount <= 0:
          print("Inavlid withdarwal amount")
        elif amount > self.__balance:
          print("Insufficient balance")
        else:
          self.__balance -= amount
          # Added print for withdraw success
          print(f"Withdrew: {amount}")

    def check_balance(self):
        # Changed to return the balance instead of just printing it
        return self.__balance

class SavingsAccount(BankAccount):
    def __init__(self, name, balance, rate):
        super().__init__(name, balance)
        self.rate = rate

    def add_interest(self):
        interest = self.check_balance() * self.rate / 100
        self.deposit(interest)


# Driver Code
acc = SavingsAccount("Ram", 10000, 5)

acc.deposit(1000)
acc.withdraw(2000)
# Now call check_balance and print its return value
print("Balance =", acc.check_balance())

acc.add_interest()
# Now call check_balance and print its return value
print("Balance after interest =", acc.check_balance())

from abc import ABC, abstractmethod

class Animal(ABC):
  @abstractmethod
  def make_sound(self):
    pass

class Dog(Animal): # Corrected: Dog is now a top-level class inheriting from Animal
  def make_sound(self):
    print("Woof!")

class Cat(Animal): # Corrected: Cat is now a top-level class inheriting from Animal
  def make_sound(self):
    print("Meow!")

