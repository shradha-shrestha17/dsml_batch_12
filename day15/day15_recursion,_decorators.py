#factorial number
#1 n*(n-1) (recursive case)
#2 1 or 0 (base case)

def factorial(n):
  if n==0 or n==1:
    return 1
  else:
    return n*factorial(n-1)

factorial(5)

#write a recursive python function fibonacci(n) that returns the nth fibonacci number

def fibonacci(n):
    if n <= 1:
        return n
    return fibonacci(n - 1) + fibonacci(n - 2)

for i in range(10):
  print(fibonacci(i), end = ",")

def fibo(n):
  if n<=1:
    return n
  else:
    return(fibo(n-1)+ fibo(n-2))

