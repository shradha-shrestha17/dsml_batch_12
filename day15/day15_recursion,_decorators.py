def myWrapper(func):
  def myInnerFunc():
    print("Inner wrapper")
    func()
  return myInnerFunc

@myWrapper
def myFunc():
  print("Hello, world!")

myFunc()

def logger(func):
  def wrapper(*args, **kwargs):
    print(f"calling {func.__name__}")
    return func(*args, **kwargs)
  return wrapper

@logger
def greet(name,age):
  print(f"Hello {name}, Age: {age}")

greet("Shradha", age = 21)

